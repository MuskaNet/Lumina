// Generates the Material 3 colour schemes for every kkRepo UI theme.
//
// Each theme keeps its existing brand colour as the M3 source colour and its
// existing accent colour as the M3 tertiary palette, so the palettes change but
// the component styling stays the MICL default.
//
// Run with `npm run build:themes` from the ui/ directory.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  Hct,
  SchemeTonalSpot,
  MaterialDynamicColors as Roles,
  TonalPalette,
  argbFromHex,
  hexFromArgb,
} from "@material/material-color-utilities";

const here = dirname(fileURLToPath(import.meta.url));
const output = resolve(here, "../src/shared/theme/themes.generated.css");

const THEMES = [
  { id: "default", brand: "#0e7c6f", accent: "#b8623f" },
  { id: "indigo", brand: "#4f46e5", accent: "#c2410c" },
  { id: "ocean", brand: "#0369a1", accent: "#0f766e" },
  { id: "sunset", brand: "#be123c", accent: "#c4320a" },
  { id: "jfrog", brand: "#16883b", accent: "#184ea0" },
  { id: "nexus", brand: "#2f7650", accent: "#2f6fa7" },
];

const ROLE_NAMES = [
  "primary",
  "onPrimary",
  "primaryContainer",
  "onPrimaryContainer",
  "primaryFixed",
  "primaryFixedDim",
  "onPrimaryFixed",
  "onPrimaryFixedVariant",
  "secondary",
  "onSecondary",
  "secondaryContainer",
  "onSecondaryContainer",
  "secondaryFixed",
  "secondaryFixedDim",
  "onSecondaryFixed",
  "onSecondaryFixedVariant",
  "tertiary",
  "onTertiary",
  "tertiaryContainer",
  "onTertiaryContainer",
  "tertiaryFixed",
  "tertiaryFixedDim",
  "onTertiaryFixed",
  "onTertiaryFixedVariant",
  "error",
  "onError",
  "errorContainer",
  "onErrorContainer",
  "background",
  "onBackground",
  "surface",
  "onSurface",
  "surfaceVariant",
  "onSurfaceVariant",
  "surfaceTint",
  "inverseSurface",
  "inverseOnSurface",
  "inversePrimary",
  "outline",
  "outlineVariant",
  "shadow",
  "scrim",
  "surfaceDim",
  "surfaceBright",
  "surfaceContainerLowest",
  "surfaceContainerLow",
  "surfaceContainer",
  "surfaceContainerHigh",
  "surfaceContainerHighest",
];

function kebab(name) {
  return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

function schemeDeclarations(brandHct, accentHct, isDark, contrastLevel) {
  const scheme = new SchemeTonalSpot(brandHct, isDark, contrastLevel);
  scheme.tertiaryPalette = TonalPalette.fromHct(accentHct);

  return ROLE_NAMES.map((role) => {
    const value = Roles[role].getArgb(scheme);
    return `  --md-sys-color-${kebab(role)}: ${hexFromArgb(value)};`;
  }).join("\n");
}

function schemeBlock(selector, declarations) {
  return `${selector} {\n${declarations}\n}\n`;
}

function indent(source, prefix = "  ") {
  return source
    .split("\n")
    .map((line) => (line ? prefix + line : line))
    .join("\n");
}

const blocks = [
  "/* Generated by ui/scripts/build-themes.mjs - do not edit by hand. */",
  "",
];

for (const theme of THEMES) {
  const brandHct = Hct.fromInt(argbFromHex(theme.brand));
  const accentHct = Hct.fromInt(argbFromHex(theme.accent));
  const selector = `:root[data-theme="${theme.id}"]`;
  const light = schemeDeclarations(brandHct, accentHct, false, 0);
  const dark = schemeDeclarations(brandHct, accentHct, true, 0);
  blocks.push(
    schemeBlock(`${selector}.light, ${selector}`, light),
    schemeBlock(`${selector}.dark`, dark),
    // Pre-paint fallback: until the theme bootstrap adds .light/.dark the first
    // paint must honour the OS scheme instead of flashing the light palette.
    `@media (prefers-color-scheme: dark) {\n  ${selector}:not(.light) {\n${indent(dark)}\n  }\n}\n`,
  );
}

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, blocks.join("\n"), "utf8");
console.log(`Wrote ${output}`);
