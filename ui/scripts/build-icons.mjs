// Subsets the self-hosted Material Symbols font down to the ligatures the UI
// actually uses, so the console never downloads the full 4 MB variable font.
//
// Run with `npm run build:icons` from the ui/ directory. Commit the generated
// src/shared/fonts/ artifacts.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { dirname, resolve, join, extname } from "node:path";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const srcDir = join(root, "src");
const fontSource = join(root, "node_modules/material-symbols/material-symbols-outlined.woff2");
const outputDir = join(srcDir, "shared/fonts");
const outputFont = join(outputDir, "material-symbols.woff2");
const outputCss = join(outputDir, "material-symbols.css");

/** Icon names produced by code rather than written inline in a template. */
const EXTRA_ICONS = [
  "unfold_more",
  "arrow_upward",
  "arrow_downward",
  "arrow_back",
  "info",
  "check",
  "check_circle",
  "error",
  "account_circle",
  "logout",
  "key",
  "inbox",
  "help",
  "archive",
  "description",
  "data_object",
  "layers",
  "help_outline",
  "folder_open",
  "folder_off",
  "search_off",
  "content_copy",
  "copy_all",
  "bolt",
  "thunderstorm",
  "warning",
  "cloud_off",
  "cloud_download",
  "download",
  "file_download",
  "close",
  "visibility",
  "visibility_off",
  "code",
  "diamond",
  "system_update_alt",
  "hub",
  "folder",
  "inventory_2",
  "deployed_code",
];

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else if ([".vue", ".ts"].includes(extname(full))) files.push(full);
  }
  return files;
}

const names = new Set(EXTRA_ICONS);

for (const file of walk(srcDir)) {
  const source = readFileSync(file, "utf8");
  for (const match of source.matchAll(/material-symbols-outlined[^>]*>\s*([a-z][a-z0-9_]*)\s*</g)) {
    names.add(match[1]);
  }
  for (const match of source.matchAll(/icon:\s*"([a-z][a-z0-9_]*)"/g)) {
    names.add(match[1]);
  }
}

const sorted = [...names].sort();
const font = await subsetFont(readFileSync(fontSource), sorted.join("\n"), {
  targetFormat: "woff2",
  variationAxes: { FILL: 0, wght: 400 },
  // Material Symbols maps icon names to glyphs through the `rlig` feature, not
  // `liga`. Retaining `rlig` also forces harfbuzz to keep the whole substitution
  // closure, which is why the subset lands around 240 KB instead of a few KB.
  keepFeatures: ["rlig"],
});

mkdirSync(outputDir, { recursive: true });
writeFileSync(outputFont, font);
writeFileSync(
  outputCss,
  `/* Generated by ui/scripts/build-icons.mjs - do not edit by hand.
 * Material Symbols Outlined (Apache-2.0), subset to: ${sorted.join(" ")}
 */
@font-face {
  font-family: "Material Symbols Outlined";
  font-style: normal;
  font-weight: 100 700;
  font-display: block;
  src: url("./material-symbols.woff2") format("woff2");
}

.material-symbols-outlined {
  font-family: "Material Symbols Outlined";
  font-weight: normal;
  font-style: normal;
  font-size: 24px;
  line-height: 1;
  letter-spacing: normal;
  text-transform: none;
  display: inline-block;
  white-space: nowrap;
  word-wrap: normal;
  direction: ltr;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
  text-rendering: optimizeLegibility;
  font-feature-settings: "liga" 1, "rlig" 1;
  -webkit-font-feature-settings: "liga", "rlig";
}
`,
  "utf8",
);

console.log(`Subset ${sorted.length} icons -> ${(font.length / 1024).toFixed(1)} KB`);
